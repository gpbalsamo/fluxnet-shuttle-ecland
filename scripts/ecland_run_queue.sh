set -u
set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd -P)"

GROUP=""
QUEUE_FILE=""
RUN_ROOT=""
ECLAND_MASTER=""
FORCING_TYPE="insitu"
NLOOP=2
NAMELIST=""
RETRIES=1

usage() {
  sed -n '/^# Usage:/,/^# (C)/p' "${BASH_SOURCE[0]}" | sed 's/^#[[:space:]]\{0,1\}//'
}

while getopts ":hg:Q:D:x:t:l:n:R:" opt; do
  case "${opt}" in
    g) GROUP="${OPTARG}" ;;
    Q) QUEUE_FILE="${OPTARG}" ;;
    D) RUN_ROOT="${OPTARG}" ;;
    x) ECLAND_MASTER="${OPTARG}" ;;
    t) FORCING_TYPE="${OPTARG}" ;;
    l) NLOOP="${OPTARG}" ;;
    n) NAMELIST="${OPTARG}" ;;
    R) RETRIES="${OPTARG}" ;;
    h) usage; exit 0 ;;
    \?) echo "ERROR: invalid option -${OPTARG}" >&2; usage >&2; exit 2 ;;
    :) echo "ERROR: option -${OPTARG} requires an argument" >&2; usage >&2; exit 2 ;;
  esac
done

for req in GROUP QUEUE_FILE RUN_ROOT ECLAND_MASTER; do
  [[ -n "${!req}" ]] || { echo "ERROR: -${req} is required" >&2; usage >&2; exit 2; }
done
[[ -f "${QUEUE_FILE}" ]] || { echo "ERROR: queue not found: ${QUEUE_FILE}" >&2; exit 1; }

STATUS_DIR="${RUN_ROOT}/status"
CLAIM_DIR="${RUN_ROOT}/claims"
LOG_DIR="${RUN_ROOT}/logs"
OUTPUT_DIR="${RUN_ROOT}/output"
WORKER="${SLURM_ARRAY_TASK_ID:-$$}"
WORK_DIR="${RUN_ROOT}/work/worker_${WORKER}"
mkdir -p "${STATUS_DIR}" "${CLAIM_DIR}" "${LOG_DIR}" "${OUTPUT_DIR}" "${WORK_DIR}"

n_ok=0; n_fail=0; n_skip=0
start=$(date +%s)
echo "worker ${WORKER} on $(hostname): draining $(grep -c . "${QUEUE_FILE}") sites from ${QUEUE_FILE}"

# The queue is read on FD 9, not stdin, and every child gets </dev/null. Both
# halves matter: a launcher such as mpirun drains the stdin it inherits, so with
# the queue on stdin a worker loses the rest of it to the first site it runs and
# exits after one. FD 9 puts the queue out of reach of anything a child does with
# descriptor 0, and </dev/null means a child that reads stdin gets EOF rather
# than another worker's share of the queue.
#
# PASSES, not one sweep. A worker re-reads the queue until a whole pass claims
# nothing, because a single pass leaves two holes, both observed here in job
# 36354918: a site whose worker died mid-run stays claimed for the rest of the
# run and has to wait for the next submission (371 sites sat orphaned that way),
# and a worker joining late walks a fully-claimed queue and exits immediately
# instead of helping (elements 1 and 3 quit after 13 s reporting "775
# skipped/claimed elsewhere"). Passes are cheap when there is nothing to do -- a
# stat per site -- and the loop still terminates promptly, since a pass that
# claims nothing means every remaining site is either done or held by a live
# worker.
pass=0
while : ; do
  pass=$((pass + 1))
  n_claimed_pass=0
  # One snapshot per pass rather than a squeue call per site: with 240 workers
  # over 775 sites the latter would be hundreds of thousands of queries.
  live_jobs=" $(squeue -h -u "${USER}" -o '%A %i' 2>/dev/null | tr '\n' ' ') "

while read -r -u 9 site; do
  [[ -n "${site}" ]] || continue
  [[ -f "${STATUS_DIR}/${site}" ]] && { n_skip=$((n_skip + 1)); continue; }

  # A claim whose owning job is gone is stale by definition: nothing is running
  # it. Reclaim by RENAMING the claim aside first -- rename is atomic and fails
  # for everyone but one worker, so two workers cannot both decide a claim is
  # stale and both proceed to run the site. A plain rm here would race.
  if [[ -d "${CLAIM_DIR}/${site}" ]]; then
    owner_job="$(awk '{print $1}' "${CLAIM_DIR}/${site}/owner" 2>/dev/null || true)"
    if [[ -n "${owner_job}" && "${owner_job}" != "local" \
          && "${live_jobs}" != *" ${owner_job} "* ]]; then
      if mv "${CLAIM_DIR}/${site}" "${CLAIM_DIR}/.stale_${site}_$$" 2>/dev/null; then
        rm -rf "${CLAIM_DIR}/.stale_${site}_$$"
        echo "reclaimed ${site} from dead job ${owner_job}"
      else
        n_skip=$((n_skip + 1)); continue
      fi
    else
      n_skip=$((n_skip + 1)); continue
    fi
  fi

  # Atomic across every worker and node: exactly one mkdir can succeed.
  mkdir "${CLAIM_DIR}/${site}" 2>/dev/null || { n_skip=$((n_skip + 1)); continue; }
  echo "${SLURM_JOB_ID:-local} $(hostname) $(date -u +%FT%TZ)" > "${CLAIM_DIR}/${site}/owner"
  n_claimed_pass=$((n_claimed_pass + 1))

  t0=$(date +%s)
  status="FAILED"
  attempt=0
  while [[ "${attempt}" -le "${RETRIES}" ]]; do
    attempt=$((attempt + 1))
    # `set -e` does not act on a command in an `if` condition, which is exactly
    # what keeps one failing site from taking the rest of the queue with it.
    if LBATCH=false "${SCRIPT_DIR}/ecland_run_experiment.sh" \
         -g "${GROUP}" \
         -t "${FORCING_TYPE}" \
         -s "${site}" \
         -x "${ECLAND_MASTER}" \
         -o "${OUTPUT_DIR}" \
         -w "${WORK_DIR}" \
         ${NAMELIST:+-n "${NAMELIST}"} \
         -l "${NLOOP}" </dev/null >> "${LOG_DIR}/${site}.log" 2>&1; then
      status="OK"
      break
    fi
    echo "attempt ${attempt} failed for ${site}" >> "${LOG_DIR}/${site}.log"
  done

  echo "${status}" > "${STATUS_DIR}/${site}"
  t1=$(date +%s)
  [[ "${status}" == "OK" ]] && n_ok=$((n_ok + 1)) || n_fail=$((n_fail + 1))
  echo "[$(date '+%H:%M:%S')] ${status} ${site} ($(( t1 - t0 ))s, attempt ${attempt})"
done 9< "${QUEUE_FILE}"

  [[ "${n_claimed_pass}" -eq 0 ]] && break
  echo "worker ${WORKER} finished pass ${pass} (${n_claimed_pass} sites claimed); re-reading the queue"
done

# NOTE on the one hole this does not close: if the LAST live worker dies mid-site,
# nobody is left to reclaim it, so that site waits for the next submission, which
# sweeps it. Keeping workers alive to cover it would mean idling up to N-1 of them
# for the length of the longest tail site -- with 240 workers and a 2.33 h record,
# about 550 CPU-hours -- so exiting when a pass claims nothing is the better trade.
echo "worker ${WORKER} done in $(( $(date +%s) - start ))s over ${pass} pass(es): ${n_ok} ok, ${n_fail} failed, ${n_skip} skipped/claimed elsewhere"
